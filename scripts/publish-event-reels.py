"""Create web-ready video, poster and available captions for approved event reels only."""
import concurrent.futures
import json
import os
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parent.parent
cache = Path(os.environ.get('UDSF_REEL_CACHE', '/tmp/udsf-reels'))
ffmpeg = os.environ.get('UDSF_FFMPEG', 'ffmpeg')
inventory = {r['id']: r for r in json.loads((cache / 'inventory.json').read_text())}
first = json.loads((root / 'data/curation/reel-review.json').read_text())['reels']
verified = json.loads((root / 'data/curation/reel-verification.json').read_text())['reels']
overrides_path = root / 'data/curation/reel-verification-overrides.json'
if overrides_path.exists():
    for ident, correction in json.loads(overrides_path.read_text()).items():
        if ident in verified:
            verified[ident].update(correction)
output = root / 'public/event-reels'
output.mkdir(exist_ok=True)
selected = [r for r in verified.values() if r['eligible'] and r['confidence'] == 'high']
selected_ids = {r['id'] for r in selected}
for asset in output.glob('reel-*'):
    if asset.is_file() and asset.stem not in selected_ids:
        asset.unlink()

def publish(review):
    record = inventory[review['id']]
    ident = record['id']
    video = output / f'{ident}.webm'
    poster = output / f'{ident}.webp'
    if not video.exists():
        subprocess.run([ffmpeg, '-v', 'error', '-y', '-threads', '1', '-i', record['source'], '-map', '0:v:0', '-map', '0:a:0?', '-vf', 'scale=720:720:force_original_aspect_ratio=decrease:force_divisible_by=2', '-c:v', 'libvpx-vp9', '-crf', '38', '-b:v', '0', '-deadline', 'good', '-cpu-used', '6', '-row-mt', '1', '-pix_fmt', 'yuv420p', '-threads', '2', '-c:a', 'libopus', '-b:a', '64k', '-cues_to_front', '1', str(video)], check=True)
    frame = first[ident]['posterFrame']
    if not poster.exists():
        subprocess.run([ffmpeg, '-v', 'error', '-y', '-i', record['frames'][frame], '-frames:v', '1', '-c:v', 'libwebp', '-quality', '82', str(poster)], check=True)
    post = dict(id=ident, title=review['title'], caption=record['caption'] or review['summary'], date=record['date'], image=f'/event-reels/{ident}.webp', video=f'/event-reels/{ident}.webm', category='events_programs')
    if record.get('subtitles', '').strip():
        text = record['subtitles'].lstrip('\ufeff').replace('\r\n', '\n')
        text = re.sub(r'(\d{2}:\d{2}:\d{2}),(\d{3})', r'\1.\2', text)
        if '-->' in text:
            (output / f'{ident}.vtt').write_text(text if text.startswith('WEBVTT') else 'WEBVTT\n\n' + text)
            post['subtitles'] = f'/event-reels/{ident}.vtt'
    print(f'Published {ident}: {review["title"]}', flush=True)
    return post

with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
    posts = sorted(pool.map(publish, selected), key=lambda p: p['date'], reverse=True)
source = 'import type { Activity } from "./activities";\n\n// Generated by scripts/publish-event-reels.py after video review.\nexport const EVENT_REELS: readonly Activity[] = ' + json.dumps(posts, ensure_ascii=False, indent=2) + ';\n'
(root / 'src/data/event-reels.ts').write_text(source)
print(f'Published {len(posts)} event reels; {sum(p.stat().st_size for p in output.iterdir()) / 1024 / 1024:.1f} MB', flush=True)
