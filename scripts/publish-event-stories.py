"""Publish hand-picked Instagram stories from the Meta export as event clips.

Stories carry no captions in the export, so each one here is chosen by eye and given its
title, caption and event date by hand. Only footage of the event itself is selected: never
election campaign stories, and never reshared posters with Instagram's story frame around them.

    UDSF_FFMPEG=/path/to/ffmpeg python3 scripts/publish-event-stories.py

UDSF_EXPORT_ROOT points at the folder holding the unzipped exports (default ~/Downloads/udsf-insta).
"""
import json
import os
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
exports = Path(os.environ.get('UDSF_EXPORT_ROOT', Path.home() / 'Downloads/udsf-insta'))
ffmpeg = os.environ.get('UDSF_FFMPEG', 'ffmpeg')
output = root / 'public/event-stories'

# source: path inside an export's media/stories folder; poster: second of the clip used as its cover
STORIES = [
    dict(source='202610/18134623687636539.mp4', poster=12.5, date='2026-10-02',
         title='Nawaf NSR Live at Thouryathrikam ’26',
         caption='Arts pro show: Nawaf NSR performing live at *Thouryathrikam ’26*, the GECW arts fest.'),
    dict(source='202610/17906639010564419.mp4', poster=6.0, date='2026-10-01',
         title='Beatz on Music with DJ Jazeel',
         caption='Arts pro show: *Beatz on Music* with DJ Jazeel at *Thouryathrikam ’26*, the GECW arts fest.'),
]


def find(source):
    for export in sorted(exports.glob('instagram-*')):
        path = export / 'media/stories' / source
        if path.is_file():
            return path
    raise FileNotFoundError(f'{source} is not in any export under {exports}')


output.mkdir(exist_ok=True)
selected = {f'story-{Path(story["source"]).stem}' for story in STORIES}
for asset in output.glob('story-*'):
    if asset.stem not in selected:
        asset.unlink()
posts = []
for story in STORIES:
    source = find(story['source'])
    ident = f'story-{source.stem}'
    video, poster = output / f'{ident}.mp4', output / f'{ident}.webp'
    if not video.exists():
        subprocess.run([ffmpeg, '-v', 'error', '-y', '-i', str(source), '-map', '0:v:0', '-map', '0:a:0?',
                        '-vf', 'scale=720:720:force_original_aspect_ratio=decrease:force_divisible_by=2',
                        '-c:v', 'libx264', '-preset', 'fast', '-crf', '28', '-pix_fmt', 'yuv420p',
                        '-c:a', 'aac', '-b:a', '80k', '-movflags', '+faststart', str(video)], check=True)
    if not poster.exists():
        subprocess.run([ffmpeg, '-v', 'error', '-y', '-ss', str(story['poster']), '-i', str(source), '-frames:v', '1',
                        '-vf', 'scale=512:512:force_original_aspect_ratio=decrease',
                        '-c:v', 'libwebp', '-quality', '82', str(poster)], check=True)
    posts.append(dict(id=ident, title=story['title'], caption=story['caption'], date=story['date'],
                      image=f'/event-stories/{ident}.webp', video=f'/event-stories/{ident}.mp4',
                      category='events_programs'))
    print(f'Published {ident}: {story["title"]}', flush=True)

(root / 'src/data/event-stories.ts').write_text(
    'import type { Activity } from "./activities";\n\n'
    '// Generated by scripts/publish-event-stories.py from hand-picked Instagram stories.\n'
    f'export const EVENT_STORIES: readonly Activity[] = {json.dumps(posts, ensure_ascii=False, indent=2)};\n')
